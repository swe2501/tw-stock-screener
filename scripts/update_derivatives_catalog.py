"""Refresh public TAIFEX stock futures catalog. No runtime API or credentials."""
import json
import re
import urllib.request
from datetime import date
from html import unescape
from pathlib import Path

SOURCES = ['https://www.taifex.com.tw/cht/2/stockLists',
           'https://www.taifex.com.tw/cht/4/contractName']
# Standard TWD specs checked against these official product pages on 2026-10-16.
# Review these explicitly when rules change; refreshing stockLists alone is insufficient.
INDEX_SPECS = dict(zip(
    ['TXF', 'MXF', 'TMF', 'EXF', 'FXF', 'XIF', 'ZEF', 'ZFF', 'G2F', 'TXO'],
    [(200, 'tX'), (50, 'mTX'), (10, 'tMF'), (4000, 'tE'), (1000, 'tF'),
     (10, 'xIF'), (500, 'zEF'), (250, 'zFF'), (50, 'g2F'), (50, 'tXO')]))


def table(url):
    text = urllib.request.urlopen(url, timeout=30).read().decode('utf-8')
    return [[unescape(re.sub('<[^>]+>', '', c)).strip()
             for c in re.findall(r'<t[dh]\b[^>]*>(.*?)</t[dh]>', row, re.S | re.I)]
            for row in re.findall(r'<tr\b[^>]*>(.*?)</tr>', text, re.S | re.I)]


def main():
    stocks, names = map(table, SOURCES)
    names = {r[1]: r[2] for r in names if len(r) == 3}
    products = []
    for r in stocks:
        if len(r) != 14 or not re.fullmatch('[A-Z]{2}', r[0]) or not r[4]:
            continue
        code = r[0] + 'F'
        if code not in names or not re.fullmatch(r'[\d,]+', r[11]):
            raise ValueError(f'Unknown standard contract: {r[0]}')
        products.append(dict(code=code, name=names[code], product='futures',
                             underlying=r[2], multiplier=int(r[11].replace(',', '')),
                             group='stock', aliases=[r[0], r[3]]))
    if len(products) < 200 or not {'CDF', 'QFF'} <= {r['code'] for r in products}:
        raise ValueError('Incomplete source; existing catalog preserved')
    # Trading-system symbols, with familiar exchange abbreviations as search aliases.
    major = [('TXF', 'TX', 'futures'), ('MXF', 'MTX', 'futures'),
             ('TMF', '', 'futures'), ('EXF', 'TE', 'futures'),
             ('FXF', 'TF', 'futures'), ('XIF', '', 'futures'),
             ('ZEF', '', 'futures'), ('ZFF', '', 'futures'),
             ('G2F', '', 'futures'), ('TXO', '', 'options')]
    entries = []
    for code, alias, product in major:
        if code not in names:
            raise ValueError(f'Missing index contract: {code}')
        multiplier, page = INDEX_SPECS[code]
        entries.append(dict(code=code, name=names[code], product=product,
                            aliases=[alias] if alias else [], group='index',
                            multiplier=multiplier, currency='TWD',
                            specSource='https://www.taifex.com.tw/cht/2/' + page,
                            specChecked='2026-10-16'))
    payload = dict(updated=str(date.today()), sources=SOURCES, products=entries + products)
    output = Path(__file__).resolve().parents[1] / 'apps/web/assets/member-derivatives-catalog.js'
    output.write_text('// Generated by scripts/update_derivatives_catalog.py; standard contracts only.\n'
                      'window.AcademyDerivativesCatalog=' + json.dumps(payload, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
    print(f'{len(entries)} index products + {len(products)} standard stock/ETF futures')


if __name__ == '__main__':
    main()
