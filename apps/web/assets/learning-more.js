  const PASS = 0.8, MAX_Q = 10;
  const taipei = (t = Date.now()) => new Date(t + 8 * 3600e3);   // 以 UTC 欄位讀台北時間
  function weekInfo(t = Date.now()) {
    const d = taipei(t), day = (d.getUTCDay() + 6) % 7;   // 週一＝0
    const monday = Date.UTC(d.getUTCFullYear(), d.getUTCMonth(), d.getUTCDate() - day) - 8 * 3600e3;   // 台北週一 00:00（UTC 毫秒）
    const th = taipei(monday + 3 * 864e5), year = th.getUTCFullYear(), jan4 = Date.UTC(year, 0, 4), j = new Date(jan4), jd = (j.getUTCDay() + 6) % 7;
    const week = Math.round((Date.UTC(year, th.getUTCMonth(), th.getUTCDate()) - (jan4 - jd * 864e5)) / (7 * 864e5)) + 1;
    return { key: `${year}-W${String(week).padStart(2, '0')}`, week, start: monday, end: monday + 7 * 864e5 - 1 };
  }
  function current(t) { const w = weekInfo(t), c = A.challenges[w.week % A.challenges.length], lessons = c.ids.map(id => A.lessons.find(l => l.id === id)).filter(Boolean); const quiz = lessons.flatMap(l => (l.quiz || []).map(q => ({ ...q, from: l.id }))).slice(0, MAX_Q); return { ...c, ...w, lessons, quiz, pass: Math.ceil(quiz.length * PASS) }; }
